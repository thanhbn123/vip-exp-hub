#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Đo GHI ĐỒNG THỜI: SQLite (một và nhiều tiến trình) so với PostgreSQL.

VÌ SAO CÓ FILE NÀY
------------------
`docs/G11_FINAL_REPORT.md` mục G11.2 nêu dấu hiệu (a) sẽ cần PostgreSQL: **nhiều tiến
trình/bản ghi cùng lúc**, vì `csdl.khoa_ghi` là một `threading.RLock` — nó chỉ phủ MỘT
tiến trình. Câu đó đúng nhưng **chưa có số**. File này sinh ra để có số.

CÁI GÌ ĐO ĐƯỢC, CÁI GÌ KHÔNG (§12.1 luật 3 — kết luận chỉ nói trong phạm vi đã đo)
----------------------------------------------------------------------------------
Bốn ca dưới đây **không dùng cùng một loại khách** (client), nên chỉ **ba cột đầu**
(số lượt hỏng · loại lỗi · có mất bản ghi không) là so sánh thẳng được giữa các ca.
Cột **ghi/giây** chỉ so được trong nhóm cùng loại khách:

| Ca | Kho | Khách | So throughput với ca nào |
|----|-----|-------|---------------------------|
| A1 | SQLite | Python `sqlite3`, nhiều THREAD, có `khoa_ghi` | A2 |
| A2 | SQLite | Python `sqlite3`, nhiều TIẾN TRÌNH (không khoá chung) | A1 |
| B1 | SQLite | `sqlite3` CLI, nhiều tiến trình | B2 |
| B2 | PostgreSQL | `psql` CLI, nhiều tiến trình | B1 |

A1↔A2 là phép đo **đúng cách mã app chạy**. B1↔B2 là phép đo **cùng loại khách**, dựng
riêng để con số ghi/giây của hai kho so được với nhau mà không bị lệch vì khách khác nhau.
So A2 với B2 về throughput là **sai phạm vi** — đừng làm.

NẰM NGOÀI phạm vi: đọc đồng thời, giao dịch nhiều câu, khoá hàng, deadlock, mạng thật
(cụm thử chạy qua socket Unix nội máy), và dữ liệu lớn.

CHẠY
----
    python3 trien_khai/postgres/do_ghi_dong_thoi.py --tien-trinh 4 --so-ghi 300
    python3 trien_khai/postgres/do_ghi_dong_thoi.py --pg-socket /tmp/vhpg.XXXX --pg-cong 55432

Không có cụm PostgreSQL thì ca B2 báo **BỎ QUA** kèm lý do, **không** báo đạt.
Dựng cụm thử: xem `trien_khai/postgres/dung_cum_thu.sh`.
"""
import argparse
import json
import multiprocessing as mp
import os
import shutil
import sqlite3
import subprocess
import sys
import tempfile
import time

DDL_SQLITE = """
PRAGMA journal_mode=WAL;
CREATE TABLE IF NOT EXISTS do_ghi (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  tho INTEGER NOT NULL,
  stt INTEGER NOT NULL,
  luc TEXT NOT NULL
);
"""
DDL_PG = """
CREATE TABLE IF NOT EXISTS do_ghi (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tho INTEGER NOT NULL,
  stt INTEGER NOT NULL,
  luc TEXT NOT NULL
);
"""


# ----------------------------------------------------------------- ca A (Python sqlite3)
def _tho_sqlite(duong_dan, tho, so_ghi, busy_ms, khoa, ket_qua, doc_truoc=False):
    """Một thợ ghi. `khoa` = None nghĩa là KHÔNG có khoá chung (ca nhiều tiến trình).

    `doc_truoc=True` mô phỏng kiểu **đọc rồi ghi trong CÙNG một giao dịch** — kiểu mà mã
    app dùng thật (`csdl.mot(...)` rồi `csdl.ghi(...)`). Đây là chỗ `busy_timeout` KHÔNG
    cứu được: khi ảnh đọc của giao dịch đã cũ, SQLite trả `SQLITE_BUSY_SNAPSHOT` NGAY,
    không chờ. Đo riêng vì nó khác hẳn ca chỉ-ghi.
    """
    hong_khoa = hong_khac = xong = 0
    # Mở kết nối cũng có thể dính khoá (`PRAGMA journal_mode` phải ghi header). Để ngoài
    # `try` thì thợ chết âm thầm và số đếm thiếu mất phần của nó — đã dính một lần khi dựng.
    try:
        kn = sqlite3.connect(duong_dan, timeout=busy_ms / 1000.0)
        kn.execute("PRAGMA busy_timeout=%d" % busy_ms)
        kn.execute("PRAGMA journal_mode=WAL")
    except Exception as e:
        ket_qua.append((0, 1 if "locked" in str(e).lower() else 0,
                        0 if "locked" in str(e).lower() else 1))
        return
    for i in range(so_ghi):
        try:
            if khoa is not None:
                khoa.acquire()
            try:
                if doc_truoc:
                    kn.execute("BEGIN")
                    kn.execute("SELECT COUNT(*) FROM do_ghi").fetchone()
                kn.execute("INSERT INTO do_ghi (tho, stt, luc) VALUES (?,?,?)",
                           (tho, i, time.strftime("%Y-%m-%d %H:%M:%S")))
                kn.commit()
                xong += 1
            finally:
                if khoa is not None:
                    khoa.release()
        except sqlite3.OperationalError as e:
            # "database is locked" / "database table is locked" — đúng thứ cần đếm.
            if "locked" in str(e).lower():
                hong_khoa += 1
            else:
                hong_khac += 1
            try:
                kn.rollback()
            except Exception:
                pass
        except Exception:
            hong_khac += 1
            try:
                kn.rollback()
            except Exception:
                pass
    kn.close()
    ket_qua.append((xong, hong_khoa, hong_khac))


def ca_a(duong_dan, so_tho, so_ghi, busy_ms, dung_thread, doc_truoc=False):
    """A1 = nhiều THREAD + `khoa_ghi` (mô phỏng đúng `csdl.khoa_ghi`).
    A2 = nhiều TIẾN TRÌNH, không có khoá nào chung — `RLock` không với tới tiến trình khác."""
    if os.path.exists(duong_dan):
        for d in ("", "-wal", "-shm"):
            if os.path.exists(duong_dan + d):
                os.remove(duong_dan + d)
    kn = sqlite3.connect(duong_dan)
    kn.executescript(DDL_SQLITE)
    kn.commit()
    kn.close()

    t0 = time.time()
    if dung_thread:
        import threading
        khoa = threading.RLock()
        ket_qua = []
        ts = [threading.Thread(target=_tho_sqlite,
                               args=(duong_dan, i, so_ghi, busy_ms, khoa, ket_qua, doc_truoc))
              for i in range(so_tho)]
        for t in ts:
            t.start()
        for t in ts:
            t.join()
    else:
        with mp.Manager() as mgr:
            ket_qua_chung = mgr.list()
            ps = [mp.Process(target=_tho_sqlite,
                             args=(duong_dan, i, so_ghi, busy_ms, None, ket_qua_chung, doc_truoc))
                  for i in range(so_tho)]
            for p in ps:
                p.start()
            for p in ps:
                p.join()
            ket_qua = list(ket_qua_chung)
    giay = time.time() - t0

    kn = sqlite3.connect(duong_dan)
    tren_dia = kn.execute("SELECT COUNT(*) FROM do_ghi").fetchone()[0]
    kn.close()
    xong = sum(r[0] for r in ket_qua)
    return {
        "mong_doi": so_tho * so_ghi, "bao_xong": xong, "tren_dia": tren_dia,
        "hong_khoa": sum(r[1] for r in ket_qua), "hong_khac": sum(r[2] for r in ket_qua),
        "giay": round(giay, 3), "ghi_moi_giay": round(xong / giay, 1) if giay else None,
        # Nếu hai số này lệch thì có lượt ghi BÁO xong mà KHÔNG có trên đĩa — hỏng im lặng.
        "khop_dia": xong == tren_dia,
    }


# ------------------------------------------------------------- ca B (CLI, so được với nhau)
def _chay_cli(lenh, sql):
    p = subprocess.Popen(lenh, stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                         stderr=subprocess.PIPE, text=True)
    out, err = p.communicate(sql)
    return p.returncode, out, err


def _sql_chen(tho, so_ghi, doc_truoc=False):
    """Sinh chuỗi câu lệnh cho một thợ CLI.

    `doc_truoc=True`: mỗi lượt là một GIAO DỊCH RIÊNG có đọc trước rồi mới ghi — đúng ca
    A3, dựng lại bằng CLI để so SQLite với PostgreSQL trên CÙNG loại khách.
    `doc_truoc=False`: cả lô nằm trong một giao dịch do nơi gọi mở (ca B1/B2).
    """
    if doc_truoc:
        return "\n".join(
            "BEGIN;\nSELECT COUNT(*) FROM do_ghi;\n"
            "INSERT INTO do_ghi (tho, stt, luc) VALUES (%d,%d,'x');\nCOMMIT;" % (tho, i)
            for i in range(so_ghi))
    return "\n".join("INSERT INTO do_ghi (tho, stt, luc) VALUES (%d,%d,'x');"
                     % (tho, i) for i in range(so_ghi))


def _tho_cli(lenh, sql, ket_qua):
    rc, out, err = _chay_cli(lenh, sql)
    khoa = err.lower().count("locked") + out.lower().count("locked")
    ket_qua.append((rc, khoa, len(err.strip().splitlines()) if err.strip() else 0))


def ca_b_sqlite(duong_dan, so_tho, so_ghi, busy_ms, doc_truoc=False):
    for d in ("", "-wal", "-shm"):
        if os.path.exists(duong_dan + d):
            os.remove(duong_dan + d)
    subprocess.run(["sqlite3", duong_dan], input=DDL_SQLITE, capture_output=True, text=True)
    dau = ".timeout %d\nPRAGMA journal_mode=WAL;\n" % busy_ms
    if not doc_truoc:
        dau += "BEGIN;\n"
    duoi = "" if doc_truoc else "\nCOMMIT;\n"
    t0 = time.time()
    with mp.Manager() as mgr:
        kq = mgr.list()
        ps = [mp.Process(target=_tho_cli,
                         args=(["sqlite3", duong_dan], dau + _sql_chen(i, so_ghi, doc_truoc) + duoi, kq))
              for i in range(so_tho)]
        for p in ps:
            p.start()
        for p in ps:
            p.join()
        kq = list(kq)
    giay = time.time() - t0
    n = int(subprocess.run(["sqlite3", duong_dan, "SELECT COUNT(*) FROM do_ghi"],
                           capture_output=True, text=True).stdout.strip() or 0)
    return {"mong_doi": so_tho * so_ghi, "tren_dia": n,
            "tien_trinh_loi": sum(1 for r in kq if r[0]), "dau_hieu_khoa": sum(r[1] for r in kq),
            "giay": round(giay, 3), "ghi_moi_giay": round(n / giay, 1) if giay else None}


def ca_b_pg(sock, cong, nguoi, csdl, so_tho, so_ghi, doc_truoc=False):
    nen = ["psql", "-h", sock, "-p", str(cong), "-U", nguoi, "-qtAX"]
    rc, _, err = _chay_cli(nen + ["-d", "postgres"],
                           "DROP DATABASE IF EXISTS %s; CREATE DATABASE %s;" % (csdl, csdl))
    if rc:
        return {"bo_qua": "không tạo được CSDL thử: " + err.strip().splitlines()[-1:][0] if err.strip() else "lỗi psql"}
    lenh = nen + ["-d", csdl]
    rc, _, err = _chay_cli(lenh, DDL_PG)
    if rc:
        return {"bo_qua": "không tạo được bảng: " + err.strip()}
    t0 = time.time()
    with mp.Manager() as mgr:
        kq = mgr.list()
        def _than(i):
            if doc_truoc:
                return _sql_chen(i, so_ghi, True)
            return "BEGIN;\n" + _sql_chen(i, so_ghi) + "\nCOMMIT;\n"

        ps = [mp.Process(target=_tho_cli, args=(lenh, _than(i), kq))
              for i in range(so_tho)]
        for p in ps:
            p.start()
        for p in ps:
            p.join()
        kq = list(kq)
    giay = time.time() - t0
    _, out, _ = _chay_cli(lenh, "SELECT COUNT(*) FROM do_ghi;")
    n = int(out.strip() or 0)
    return {"mong_doi": so_tho * so_ghi, "tren_dia": n,
            "tien_trinh_loi": sum(1 for r in kq if r[0]), "dau_hieu_khoa": sum(r[1] for r in kq),
            "giay": round(giay, 3), "ghi_moi_giay": round(n / giay, 1) if giay else None}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tien-trinh", type=int, default=4)
    ap.add_argument("--so-ghi", type=int, default=300)
    ap.add_argument("--pg-socket", default=os.environ.get("VHPG_SOCKET", ""))
    ap.add_argument("--pg-cong", type=int, default=int(os.environ.get("VHPG_CONG", "55432")))
    ap.add_argument("--pg-nguoi", default=os.environ.get("VHPG_NGUOI", "vhtest"))
    ap.add_argument("--json", default="")
    t = ap.parse_args()

    tmp = tempfile.mkdtemp(prefix="do-ghi-")
    db = os.path.join(tmp, "do.db")
    ra = {"tien_trinh": t.tien_trinh, "so_ghi_moi_tho": t.so_ghi,
          "tong_luot_ghi": t.tien_trinh * t.so_ghi, "may": os.uname().machine,
          "python": sys.version.split()[0], "sqlite": sqlite3.sqlite_version}
    try:
        print("== A1 · SQLite · nhiều THREAD + khoá chung (đúng mô hình `csdl.khoa_ghi`)")
        ra["A1_sqlite_thread_co_khoa"] = ca_a(db, t.tien_trinh, t.so_ghi, 10000, True)
        print("  ", json.dumps(ra["A1_sqlite_thread_co_khoa"], ensure_ascii=False))

        print("== A2a · SQLite · nhiều TIẾN TRÌNH · busy_timeout=10000ms (giá trị csdl.mo dùng)")
        ra["A2a_sqlite_tien_trinh_bt10000"] = ca_a(db, t.tien_trinh, t.so_ghi, 10000, False)
        print("  ", json.dumps(ra["A2a_sqlite_tien_trinh_bt10000"], ensure_ascii=False))

        print("== A2b · SQLite · nhiều TIẾN TRÌNH · busy_timeout=0ms (cho thấy tranh chấp thô)")
        ra["A2b_sqlite_tien_trinh_bt0"] = ca_a(db, t.tien_trinh, t.so_ghi, 0, False)
        print("  ", json.dumps(ra["A2b_sqlite_tien_trinh_bt0"], ensure_ascii=False))

        print("== A3 · SQLite · nhiều TIẾN TRÌNH · ĐỌC rồi GHI trong cùng giao dịch "
              "(busy_timeout=10000ms) — kiểu mã app dùng thật")
        ra["A3_sqlite_tien_trinh_doc_roi_ghi"] = ca_a(db, t.tien_trinh, t.so_ghi, 10000,
                                                      False, doc_truoc=True)
        print("  ", json.dumps(ra["A3_sqlite_tien_trinh_doc_roi_ghi"], ensure_ascii=False))

        print("== B1 · SQLite · sqlite3 CLI nhiều tiến trình")
        ra["B1_sqlite_cli"] = ca_b_sqlite(db, t.tien_trinh, t.so_ghi, 10000)
        print("  ", json.dumps(ra["B1_sqlite_cli"], ensure_ascii=False))

        print("== B2 · PostgreSQL · psql nhiều tiến trình")
        thieu_pg = None
        if not t.pg_socket:
            thieu_pg = "chưa truyền --pg-socket (hoặc biến môi trường VHPG_SOCKET)"
        elif not shutil.which("psql"):
            thieu_pg = "không tìm thấy lệnh `psql` trên PATH"
        if thieu_pg:
            ra["B2_postgres_cli"] = {"bo_qua": thieu_pg + " — KHÔNG kết luận gì về PostgreSQL"}
        else:
            ra["B2_postgres_cli"] = ca_b_pg(t.pg_socket, t.pg_cong, t.pg_nguoi,
                                            "vh_do_ghi", t.tien_trinh, t.so_ghi)
        print("  ", json.dumps(ra["B2_postgres_cli"], ensure_ascii=False))

        # B3 ↔ B4 là CẶP SO ĐƯỢC cho ca đọc-rồi-ghi: cùng loại khách (CLI), cùng số lượt,
        # cùng máy. Đây là chỗ A3 cho thấy SQLite gãy — xem PostgreSQL có gãy như vậy không.
        print("== B3 · SQLite · sqlite3 CLI · ĐỌC rồi GHI, mỗi lượt một giao dịch")
        ra["B3_sqlite_cli_doc_roi_ghi"] = ca_b_sqlite(db, t.tien_trinh, t.so_ghi, 10000,
                                                      doc_truoc=True)
        print("  ", json.dumps(ra["B3_sqlite_cli_doc_roi_ghi"], ensure_ascii=False))

        print("== B4 · PostgreSQL · psql · ĐỌC rồi GHI, mỗi lượt một giao dịch")
        if thieu_pg:
            ra["B4_postgres_cli_doc_roi_ghi"] = {"bo_qua": thieu_pg}
        else:
            ra["B4_postgres_cli_doc_roi_ghi"] = ca_b_pg(
                t.pg_socket, t.pg_cong, t.pg_nguoi, "vh_do_ghi2",
                t.tien_trinh, t.so_ghi, doc_truoc=True)
        print("  ", json.dumps(ra["B4_postgres_cli_doc_roi_ghi"], ensure_ascii=False))
    finally:
        shutil.rmtree(tmp, ignore_errors=True)

    if t.json:
        with open(t.json, "w", encoding="utf-8") as f:
            json.dump(ra, f, ensure_ascii=False, indent=1)
        print("\nĐã ghi:", t.json)
    return 0


if __name__ == "__main__":
    sys.exit(main())
