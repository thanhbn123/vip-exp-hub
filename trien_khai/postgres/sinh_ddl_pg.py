#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Sinh DDL PostgreSQL TỪ chính schema SQLite đang chạy — không chép thành bản thứ hai.

VÌ SAO SINH CHỨ KHÔNG CHÉP
--------------------------
`app/migrate.py` hàm `nang_len_v8` đã nêu đúng lý do cho trường hợp của nó: *"Chép sang đây
là tạo bản thứ hai, và hai bản nội dung là hai bản sẽ lệch nhau."* Một file `schema_pg.sql`
viết tay sẽ đúng hôm nay và sai lặng lẽ ở lần một agent thêm cột. File này đọc thẳng
`csdl.SCHEMA` + năm hằng `DDL_G0x` rồi dịch, nên nó **không thể cũ hơn** mã.

PHẠM VI — ĐỌC KỸ TRƯỚC KHI TIN
------------------------------
Đây là **bản dịch DDL**, KHÔNG phải một lượt chuyển CSDL. Nó phục vụ đúng một việc: trả lời
câu *"schema này có chạy trên PostgreSQL không, và phải sửa những gì"* bằng số đo thay vì
bằng phỏng đoán. Nó **không** chuyển dữ liệu, **không** đụng `app/du-lieu/hub.db`, và
**không** đổi `app/csdl.py`.

Theo quyết định **D-8 (anh Thành, 15/10/2026)**: *tiếp tục SQLite local; THỬ PostgreSQL
trước khi quyết định.* **Thử thì được, chuyển thì không.**

BỐN PHÉP DỊCH — và chỉ bốn
--------------------------
Bốn phép này là **toàn bộ** chỗ DDL hiện tại không chạy nguyên văn trên PostgreSQL 16.
Con số đó do đo, không do đoán: xem `docs/G12_POSTGRES.md` mục 2.

1. `INTEGER PRIMARY KEY AUTOINCREMENT` → `BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY`
2. `CREATE TRIGGER IF NOT EXISTS … BEGIN SELECT RAISE(ABORT,'…'); END;`
   → hàm PL/pgSQL `RAISE EXCEPTION` + `DROP TRIGGER IF EXISTS` + `CREATE TRIGGER … FOR EACH ROW`
3. `BLOB` → `BYTEA`
4. **Thứ tự bảng**: SQLite cho khai `REFERENCES roles(ma)` TRƯỚC khi `roles` tồn tại;
   PostgreSQL không. Phép này là ĐỔI THỨ TỰ, không phải thay chữ — xem `_sap_thu_tu`.

Những thứ **KHÔNG cần dịch** (đã đo, chạy nguyên văn): partial unique index
(`CREATE UNIQUE INDEX … WHERE …`), mọi `CHECK (…)` kể cả `length(x) > 0`,
`ON CONFLICT(col) DO UPDATE SET … excluded.…`, `UNIQUE (a, b)`, `TEXT`, `INTEGER`.

CHẠY
----
    python3 trien_khai/postgres/sinh_ddl_pg.py            # in ra màn hình
    python3 trien_khai/postgres/sinh_ddl_pg.py -o /tmp/schema_pg.sql
"""
import argparse
import os
import re
import sys

GOC_APP = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(
    os.path.abspath(__file__)))), "app")


def _nap_nguon():
    """Trả danh sách (tên bộ, chuỗi DDL) lấy TỪ MÃ ĐANG CHẠY, không từ bản chép."""
    if GOC_APP not in sys.path:
        sys.path.insert(0, GOC_APP)
    import csdl
    import ai_job
    import goi_dich_vu
    import harness_hang
    import quan_sat
    import tai_chinh
    return [
        ("csdl.SCHEMA (lõi v8)", csdl.SCHEMA),
        ("tai_chinh.DDL_G07", tai_chinh.DDL_G07),
        ("goi_dich_vu.DDL_G08", goi_dich_vu.DDL_G08),
        ("harness_hang.DDL_G09", harness_hang.DDL_G09),
        ("ai_job.DDL_G10", ai_job.DDL_G10),
        ("quan_sat.DDL_G11", quan_sat.DDL_G11),
    ]


def bo_chu_thich(sql):
    ra = []
    for d in sql.split("\n"):
        i = d.find("--")
        if i >= 0:
            d = d[:i]
        ra.append(d)
    return "\n".join(ra)


def tach_cau(sql):
    """Tách thành từng câu. Thân trigger `BEGIN … END;` chứa dấu `;` nên không cắt ở đó."""
    sql = bo_chu_thich(sql)
    cau, hien, trong_trigger, sau_begin = [], [], False, False
    for ch in sql:
        hien.append(ch)
        if ch != ";":
            continue
        t = "".join(hien).strip()
        tu = t.upper()
        if not trong_trigger and re.match(r"CREATE\s+TRIGGER", tu):
            trong_trigger = True
        if trong_trigger:
            if re.search(r"\bBEGIN\b", tu):
                sau_begin = True
            if not (sau_begin and re.search(r"\bEND\s*;\s*$", tu)):
                continue
            trong_trigger = sau_begin = False
        if t.strip(";").strip():
            cau.append(t)
        hien = []
    con = "".join(hien).strip()
    if con.strip(";").strip():
        cau.append(con)
    return cau


def dich_cau(cau):
    """Ba phép thay chữ. Phép thứ tư (thứ tự bảng) xử ở `_sap_thu_tu`."""
    t = re.sub(r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b",
               "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", cau, flags=re.I)
    m = re.match(r"\s*CREATE\s+TRIGGER\s+IF\s+NOT\s+EXISTS\s+(\w+)\s+BEFORE\s+(UPDATE|DELETE)"
                 r"\s+ON\s+(\w+)\s+BEGIN\s+SELECT\s+RAISE\(\s*ABORT\s*,\s*'([^']*)'\s*\)\s*;"
                 r"\s*END\s*;?\s*$", t, flags=re.I | re.S)
    if m:
        ten, khi, bang, thong_diep = m.group(1), m.group(2).upper(), m.group(3), m.group(4)
        # RAISE EXCEPTION của PL/pgSQL huỷ GIAO DỊCH, còn RAISE(ABORT) của SQLite chỉ huỷ
        # CÂU LỆNH. Khác biệt này có thật và phải biết — xem docs/G12_POSTGRES.md mục 2.4.
        return (f"CREATE OR REPLACE FUNCTION fn_{ten}() RETURNS trigger AS $$\n"
                f"BEGIN RAISE EXCEPTION '{thong_diep}'; END;\n$$ LANGUAGE plpgsql;\n"
                f"DROP TRIGGER IF EXISTS {ten} ON {bang};\n"
                f"CREATE TRIGGER {ten} BEFORE {khi} ON {bang}\n"
                f"  FOR EACH ROW EXECUTE FUNCTION fn_{ten}();")
    # BLOB chỉ đổi khi đứng một mình như tên kiểu, không đổi trong chuỗi hay tên cột.
    return re.sub(r"(?<![\w'])BLOB(?![\w'])", "BYTEA", t)


# Phép 4: cặp (bảng phải có trước, bảng tham chiếu tới nó). SQLite cho tham chiếu tiến;
# PostgreSQL đòi bảng đích tồn tại ngay lúc `CREATE TABLE`. Danh sách này là ĐEN có chủ ý:
# thiếu một cặp thì lượt chạy BÁO LỖI ngay (relation does not exist), không hỏng im lặng.
CAP_THU_TU = [("roles", "tenant_memberships")]


def _sap_thu_tu(cau):
    ra = list(cau)

    def vi_tri(ten):
        for j, c in enumerate(ra):
            if re.search(r"CREATE\s+TABLE\s+(IF\s+NOT\s+EXISTS\s+)?%s\b" % ten, c, re.I):
                return j
        return None

    for truoc, sau in CAP_THU_TU:
        a, b = vi_tri(truoc), vi_tri(sau)
        if a is not None and b is not None and a > b:
            ra.insert(b, ra.pop(a))
    return ra


def sinh():
    """Trả (văn bản DDL PostgreSQL, thống kê)."""
    cau, nguon = [], []
    for ten, ddl in _nap_nguon():
        for c in tach_cau(ddl):
            cau.append(c)
            nguon.append(ten)
    cau = _sap_thu_tu(cau)
    than = [dich_cau(c) for c in cau]
    dong = [
        "-- DDL PostgreSQL SINH TỰ ĐỘNG bởi trien_khai/postgres/sinh_ddl_pg.py",
        "-- Nguồn: app/csdl.py SCHEMA + 5 hằng DDL_G07…DDL_G11. ĐỪNG SỬA FILE NÀY BẰNG TAY —",
        "-- sửa ở module nguồn rồi sinh lại, nếu không sẽ có hai bản và hai bản sẽ lệch nhau.",
        "-- Đây là BẢN DỊCH ĐỂ THỬ (D-8). KHÔNG phải một lượt chuyển CSDL.",
        "",
    ]
    return "\n".join(dong) + "\n\n".join(t.rstrip().rstrip(";") + ";" for t in than) + "\n", {
        "so_cau": len(cau),
        "so_bo_nguon": len(set(nguon)),
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-o", "--ra", default="")
    t = ap.parse_args()
    vb, tk = sinh()
    if t.ra:
        with open(t.ra, "w", encoding="utf-8") as f:
            f.write(vb)
        print("Đã ghi %s — %d câu từ %d bộ nguồn" % (t.ra, tk["so_cau"], tk["so_bo_nguon"]))
    else:
        sys.stdout.write(vb)
    return 0


if __name__ == "__main__":
    sys.exit(main())
